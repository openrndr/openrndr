#!/usr/bin/env python3
"""
Generates UnicodeTables.kt for openrndr-bidi-text-driver from the Unicode Character Database.

Usage:
    python3 generate_unicode_tables.py [--version 18.0.0] [--ucd <directory with UCD files>]

Without --ucd the files are downloaded from https://www.unicode.org/Public/<version>/ucd/.
Needed files: extracted/DerivedBidiClass.txt, BidiBrackets.txt, BidiMirroring.txt, Scripts.txt,
PropertyValueAliases.txt.

The tables are emitted as run-length encoded strings so they don't run into JVM method size limits:
each entry is `<hex start>:<value>` and entries are separated by `,`. A run extends to the next entry.
"""

import argparse
import os
import urllib.request

OUTPUT = os.path.join(os.path.dirname(__file__), "..", "src", "commonMain", "kotlin", "UnicodeTables.kt")

# Must match the declaration order of org.openrndr.draw.font.internal.BidiClass
BIDI_CLASSES = ["L", "R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S", "WS", "ON",
                "LRE", "LRO", "RLE", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI"]

FILES = ["extracted/DerivedBidiClass.txt", "BidiBrackets.txt", "BidiMirroring.txt", "Scripts.txt",
         "PropertyValueAliases.txt"]


def read_lines(args, name):
    if args.ucd:
        path = os.path.join(args.ucd, name)
        if not os.path.exists(path):
            path = os.path.join(args.ucd, os.path.basename(name))
        with open(path, encoding="utf-8") as f:
            return f.read().splitlines()
    url = f"https://www.unicode.org/Public/{args.version}/ucd/{name}"
    with urllib.request.urlopen(url) as r:
        return r.read().decode("utf-8").splitlines()


def parse_range(r):
    start, _, end = r.strip().partition("..")
    start = int(start, 16)
    return start, int(end, 16) if end else start


def property_aliases(lines, prop):
    aliases = {}
    for line in lines:
        fields = [f.strip() for f in line.split("#")[0].split(";")]
        if len(fields) >= 3 and fields[0] == prop:
            for alias in fields[1:]:
                aliases[alias] = fields[1]
    return aliases


def load_property(lines, aliases, default):
    values = [default] * 0x110000
    # @missing lines come first in order of increasing specificity
    for line in lines:
        if line.startswith("# @missing:"):
            r, v = line[len("# @missing:"):].split(";")
            s, e = parse_range(r)
            values[s:e + 1] = [aliases[v.strip()]] * (e - s + 1)
    for line in lines:
        line = line.split("#")[0].strip()
        if not line:
            continue
        r, v = line.split(";")
        s, e = parse_range(r)
        values[s:e + 1] = [aliases[v.strip()]] * (e - s + 1)
    return values


def run_length_encode(values, encode):
    entries = []
    previous = None
    for cp, v in enumerate(values):
        if v != previous:
            entries.append(f"{cp:X}:{encode(v)}")
            previous = v
    return ",".join(entries)


def kotlin_string(name, data):
    # split over multiple lines for readability, the compiler folds the concatenation into one constant
    chunks = [data[i:i + 100] for i in range(0, len(data), 100)]
    body = " +\n    ".join(f'"{c}"' for c in chunks)
    return f"internal const val {name} =\n    {body}\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--version", default="18.0.0")
    parser.add_argument("--ucd", help="directory containing the UCD files")
    args = parser.parse_args()

    value_aliases = read_lines(args, "PropertyValueAliases.txt")

    bc_aliases = property_aliases(value_aliases, "bc")
    bidi = load_property(read_lines(args, "extracted/DerivedBidiClass.txt"), bc_aliases, "L")
    bidi_data = run_length_encode(bidi, lambda v: BIDI_CLASSES.index(v))

    sc_aliases = property_aliases(value_aliases, "sc")
    scripts = load_property(read_lines(args, "Scripts.txt"), sc_aliases, "Zzzz")
    script_tags = sorted(set(scripts))
    script_data = run_length_encode(scripts, lambda v: script_tags.index(v))

    brackets = []
    for line in read_lines(args, "BidiBrackets.txt"):
        line = line.split("#")[0].strip()
        if line:
            cp, paired, kind = [f.strip() for f in line.split(";")]
            brackets.append(f"{int(cp, 16):X}:{int(paired, 16):X}:{kind}")

    mirrors = []
    for line in read_lines(args, "BidiMirroring.txt"):
        line = line.split("#")[0].strip()
        if line:
            cp, mirror = [f.strip() for f in line.split(";")]
            mirrors.append(f"{int(cp, 16):X}:{int(mirror, 16):X}")

    with open(OUTPUT, "w", encoding="utf-8") as f:
        f.write("// Generated by generator/generate_unicode_tables.py from the Unicode Character Database, do not edit.\n")
        f.write(f"// Unicode version {args.version}\n\n")
        f.write("package org.openrndr.biditextdriver\n\n")
        f.write(f'internal const val UNICODE_VERSION = "{args.version}"\n\n')
        f.write("/** Bidi_Class runs, `<hex start>:<BidiClass ordinal>` */\n")
        f.write(kotlin_string("BIDI_CLASS_DATA", bidi_data))
        f.write("\n/** ISO 15924 tags indexed by the values in [SCRIPT_DATA] */\n")
        f.write("internal val SCRIPT_TAGS = arrayOf(" + ", ".join(f'"{t}"' for t in script_tags) + ")\n\n")
        f.write("/** Script runs, `<hex start>:<index in SCRIPT_TAGS>` */\n")
        f.write(kotlin_string("SCRIPT_DATA", script_data))
        f.write("\n/** Bidi_Paired_Bracket and Bidi_Paired_Bracket_Type, `<hex code point>:<hex paired bracket>:<o|c>` */\n")
        f.write(kotlin_string("BIDI_BRACKET_DATA", ",".join(brackets)))
        f.write("\n/** Bidi_Mirroring_Glyph, `<hex code point>:<hex mirrored code point>` */\n")
        f.write(kotlin_string("BIDI_MIRRORING_DATA", ",".join(mirrors)))

    print(f"bidi runs: {len(bidi_data.split(','))}, script runs: {len(script_data.split(','))}, "
          f"brackets: {len(brackets)}, mirrors: {len(mirrors)}")


if __name__ == "__main__":
    main()
